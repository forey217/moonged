"""Rebuild the runtime table from the pinned official GEDCOM 7.0.18 TSVs.
No network, PyYAML, or runtime Python dependency is required.
"""
import pathlib, json, hashlib
root = pathlib.Path(__file__).resolve().parents[1]
src = root / 'spec/gedcom-7.0.18'
base = 'https://gedcom.io/terms/v7/'
def rows(name):
    return [s.split('\t') for s in (src / name).read_text().splitlines()]
def short(s): return s.removeprefix(base)
def q(s): return json.dumps(s, ensure_ascii=False)
enums = json.loads((src / 'enum-tags.json').read_text())
members = dict(rows('enumerations.tsv'))
cards = {(p,t): c for p,t,c in rows('cardinalities.tsv')}
types = dict(rows('payloads.tsv'))
types.pop(base + 'CONT',None)
out = ['// Generated by scripts/generate-schema.py. Do not edit.',
       '// Derived from FamilySearch GEDCOM 7.0.18, Apache-2.0; see spec/gedcom-7.0.18/NOTICE.',
       '///|', 'let standard_payloads : Map[String, (String, Array[String])] = Map([']
for uri, payload in sorted(types.items()):
    vals = sorted(enums[members[uri]]) if uri in members else []
    payload = short(payload).replace('http://www.w3.org/2001/XMLSchema#', 'xsd:').replace('http://www.w3.org/ns/dcat#','dcat:')
    if payload.startswith('@<'): payload = 'pointer:' + short(payload[2:-2])
    out.append('  (' + q(short(uri)) + ', (' + q(payload) + ', [' + ', '.join(map(q,vals)) + '])),')
out += ['])', '///|', 'let standard_children : Map[String, Array[(String, String, Bool, Bool)]] = Map([']
groups = {}
for p, tag, t in rows('substructures.tsv'):
    if tag == 'CONT': continue  # parser folds pseudo-structures into payloads
    c = ('{1:1}' if tag in ('HEAD','TRLR') else '{0:M}') if not p else cards[p,t]
    groups.setdefault(short(p), []).append((tag,short(t),c[1]=='1',c[-2]=='1'))
for p, edges in sorted(groups.items()):
    out += ['  (' + q(p) + ', [']
    for tag,t,required,singular in sorted(edges):
        out.append('    (' + q(tag) + ', ' + q(t) + ', ' + str(required).lower() + ', ' + str(singular).lower() + '),')
    out += ['  ]),']
out += ['])','///|','let standard_enum_uris : Map[String, Array[String]] = Map([']
for uri, eset in sorted(members.items()):
    out.append('  (' + q(short(uri)) + ', [' + ', '.join(map(q,sorted(enums[eset].values()))) + ']),')
out += ['])','']
(root / 'schema_data.mbt').write_text('\n'.join(out), encoding='utf-8', newline='\n')
manifest = {p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(src.iterdir(),key=lambda p:p.name.casefold()) if p.is_file() and p.name != 'provenance.json'}
report = {'specification':'7.0.18','structures':len(types),'parent_child_rules':sum(map(len,groups.values())), 'enum_sets':len(enums), 'sources':manifest}
(src / 'provenance.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8',newline='\n')
print(json.dumps({k:v for k,v in report.items() if k!='sources'}))
